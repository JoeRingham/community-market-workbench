"""Golden test: the full raw-extraction output for the synthetic Van-Whole-format
list must not drift.

`synthetic.pdf` is generated by generate_synthetic.py - same page size, column
geometry, letterhead strings, and letter-spaced headers as the real format, but
every product, price, and code is fabricated. Safe to publish; exercises
pricelistparser.suppliers.van_whole exactly as shipped.

Regenerate both files after a deliberate parser change:

    cd pricelistparser
    uv run python tests/fixtures/van_whole/generate_synthetic.py
    uv run pricelistparser tests/fixtures/van_whole/synthetic.pdf \
        --supplier van_whole --pretty > tests/fixtures/van_whole/synthetic.expected.json

A real historical price list may also be dropped in this directory for local,
uncommitted testing against real data (see fixtures/README.md) - .gitignore
excludes everything here except the files this test uses.
"""

from __future__ import annotations

import json
import pathlib

import pdfplumber

from pricelistparser import parse_pricelist
from pricelistparser.dispatch import detect

FIX = pathlib.Path(__file__).parent / "fixtures" / "van_whole"
PDF = FIX / "synthetic.pdf"
EXPECTED = FIX / "synthetic.expected.json"


def test_output_matches_golden():
    got = parse_pricelist(str(PDF), supplier="van_whole").to_dict()
    expected = json.loads(EXPECTED.read_text())
    assert got == expected


def test_sniff_identifies_van_whole():
    with pdfplumber.open(str(PDF)) as pdf:
        slug, confidence = detect(pdf)
    assert slug == "van_whole"
    assert confidence >= 0.9


def test_invariants():
    """Cheap structural guarantees independent of the golden snapshot."""
    result = parse_pricelist(str(PDF), supplier="van_whole")
    assert result.meta.currency == "CAD"
    assert result.meta.effective_from and result.meta.effective_to
    assert result.meta.row_count == len(result.rows)
    assert result.meta.data_pages == [2, 3]  # page 1 is the non-data cover

    for r in result.rows:
        assert r.column in ("left", "right")
        assert r.description, "every emitted row has a description"
        assert r.price_basis in ("case", "lb", "each")
        # a row either has a numeric price, or is explicitly unavailable (N/A)
        assert (r.price is not None) or r.unavailable or r.price_raw is None
        if r.price is not None:
            assert 0 < r.price < 5000


def test_covers_known_edge_cases():
    """The fixture is built to exercise every documented parsing quirk; assert
    each one actually fired, so a future refactor can't silently stop covering
    a case just because the golden snapshot still happens to match."""
    result = parse_pricelist(str(PDF), supplier="van_whole")
    by_desc = {r.description: r for r in result.rows}

    # organic banner prefixes the section on that page only
    assert by_desc["AVOCADOS ORGANIC MEX 20S"].section == "ORGANIC - FRUITS"
    assert by_desc["MANGOS PREMIUM MEX 10S"].section == "FRUITS"  # not organic on page 3

    # PER LB -> price_basis
    assert by_desc["GINGER ROOT PERU PER LB"].price_basis == "lb"

    # N/A -> unavailable, price None
    turmeric = by_desc["TURMERIC ROOT ORGANIC 12X227G"]
    assert turmeric.unavailable is True
    assert turmeric.price is None

    # embedded code -> supplier_sku
    assert by_desc["MUSHROOMS WHITE NO1 BC (48213)"].supplier_sku == "48213"

    # price wrapped onto its own sub-line got merged back onto the description
    merged = by_desc["SALAD MIX BABY GREENS (E.B.) 5510097"]
    assert merged.price == 29.75
    assert merged.supplier_sku == "5510097"

    # a section name outside the canonical list still passes through, flagged
    assert any(w.code == "unknown_section" and w.detail == "MUSHROOMS" for w in result.warnings)

    # right column's running section starts fresh from its own header, not the
    # left column's trailing section
    assert by_desc["PEPPERS RED BC 11LBS"].section == "VEGETABLES"
